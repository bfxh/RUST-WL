use super::*;

/// **解算前**的冲击快照（破坏管线消费；见 `World::record_impacts`）。
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ImpactRecord {
    /// provider id（体素/网格/喷溅同 id 空间）。
    pub provider: u32,
    /// 冲击体（动态体）索引。
    pub body: u32,
    /// 接触点（流形点均值，世界系）。
    pub point: Vec3,
    /// 沿接触法向的接近速度（m/s，> 0 表示正在靠近）。
    pub approach: f32,
    /// 该体解算前的速度（挖坑方向用）。
    pub velocity: Vec3,
}

