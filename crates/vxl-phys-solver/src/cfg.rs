/// **切向回拉的粘着判定阈值**：`|pt| ≥ 此值 × μ·pn` ⇒ 该接触视为**滑动**、不做切向回拉。
///
/// 依据（`OPEN-PROBLEMS.md` P1）：滑动接触的锚点分离**就是**真实材料滑移，回拉等于
/// **抹掉真实滑动**、且因力臂而 ∝ μ 地注入转矩——那是角向残差的主项（实测塔角向超阈
/// 202→93、总数 406→269）；粘着接触的分离才是数值错位，才是回拉的正当对象。
/// 判定用**上一子步的暖启动冲量**（零额外状态、不需材料查表）。
/// 实测该阈值 0.99 在各轴上最好（0.90 全面变差：角 122→137、总数 247→315）。
pub(crate) const DRIFT_STICK_RATIO: f32 = 0.99;

/// **子块睡眠（逐体入睡）**：`true`（默认）= 三件一起生效：① **逐体计时**（各自累加/清零，
/// 取代"整岛一起清零"）；② **逐体入睡**（不要求整岛齐）；③ **唤醒改为"实质相互作用"**
/// （连通本身不唤醒，带滞回），且求解期把睡眠体**按静态处理**（否则"位置冻结、速度被写"）。
///
/// **为什么**（`PLAN-solver-limits.md` / `OPEN-PROBLEMS.md` P1）：岛级原子入睡被**极少数**仍在
/// 微动的体卡死——实测**逐体超阈仅 2.21%**（每子步约 50/2500 体），而 2500 体的岛出现
/// ≥1 个超阈体的概率是 `1 − 0.978^2500 ≈ 100%` ⇒ 整岛门被 2% 的尾巴拒绝。
/// 落地读数（塔 2400 tick、参考配方 `16/1/16`）：**超阈 483 → 1**、**入睡 0 → 2396/2500（96%）**、
/// **KE ~99 J → 1.2 J**；代价 Δpos max 0.0849 → 0.0950（+12%）；稳定（y 带完整、无发散）。
pub(crate) const SUBISLAND_SLEEP: bool = true;

/// 唤醒**滞回**倍数：闪烁体的接触面速度（`ω×r ≈ 0.0125–0.05 m/s`）正卡在睡眠阈值上，
/// 若唤醒阈值与睡眠阈值相同，边界体每子步都会被叫醒 ⇒ 子块睡眠失效。取 2×。
pub(crate) const SUBISLAND_WAKE_MULT: f32 = 2.0;
/// **强撞直通**（配合 `PhysConfig::wake_gate_k`）：相对速度 ≥ 本系数 ×`sleep_linear`
/// 时**无条件立即唤醒**，不经接触数门。
///
/// 为什么必须有（2026-09-22 分析 + 探针）：门是**硬条件**（同一次 `solve_phase` 内 ≥K 条
/// hot 观测），而**孤立睡体被撞**只有 1 条 hot 接触 ⇒ K>0 时它**永不醒**、变成"隐形墙"
/// （撞它的体像撞静态体一样弹开，而睡体自己不响应）。这条把"真撞击"与"轻碰抖动"分开：
/// 轻碰（<本阈值）累积到 K 才醒，强撞立即醒。
pub(crate) const WAKE_GATE_FAST_MULT: f32 = 8.0;

/// **逐岛解算三段计时**（`IslandDiag.build/warm/iter` 的每岛探针）：每岛要读 **6 次时钟**
